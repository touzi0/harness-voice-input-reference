// 判定与位置的四个要点（这也是"为什么这样注入"的答案）
//
// 1) 怎么判断"这次是语音输入"：
//    完全不靠猜内容、不靠启发式。链路是 ①落框打 dataset 标记 → ②发送时读标记
//    上报 voiceUsed → ③后端置位会话粘性标记 m.VoiceUsed → ④这里读 sess.VoiceUsed。
//    前端标记是唯一的事实来源；后端不重新判断（后端也判断不了——它只收到一段文本）。
//
// 2) 为什么加在「环境快照」而不是系统提示词里：
//    系统提示词是稳定前缀，按会话身份拼一次、之后逐字不变，才能吃满前缀缓存；
//    而"用户用过语音"是会话级的可变状态。放进环境快照，模型照样第 0 轮就看见，
//    但改动只影响追加在历史尾部的差分消息，前缀一个字节不动。
//
// 3) 为什么是粘性（一次置位、终身有效）+ 差分下发：
//    见 ③ 的注释。要点是快照逐字稳定 → 这一行只在置位那一次产生一次「环境更新」，
//    此后每轮组装结果完全相同，不产生任何额外的上下文开销（≈ 一次性 40 token）。
//
// 4) 为什么措辞是"请按上下文理解其本意…不必特意指出"：
//    · "按上下文理解其本意" —— 给出处理方式，而不是把判断留给模型自由发挥；
//    · "在回复中自然使用正确写法" —— 明确允许它在心里换字（用户要的是结果对），
//      但不许把用户的原话改写后再展示成"你说过的话"；
//    · "不必特意指出" —— 避免模型每次都回一句"我理解你可能说的是接口而不是借口"，
//      这种纠错播报对用户是噪音，也把话题带偏；
//    · 整行只描述**输入的来源与质量**，不描述用户是谁、不描述任务——
//      提示词里每一行都该只讲一件事，混在一起就无法被差分引擎单独增删。
